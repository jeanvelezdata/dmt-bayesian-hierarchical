def plot_shrinkage():
    """
    Shrinkage plot: no-pooling estimate (x) vs. hierarchical estimate (y).

    Each point is one outcome measure, labelled by name.
    A dashed diagonal y = x marks zero shrinkage.
    A dotted horizontal line shows the global posterior mean β (the target
    toward which partial pooling shrinks every measure-level estimate).
    Blue arrows run vertically from the no-pooling position on the diagonal
    to the hierarchical posterior mean, visually showing how much each
    measure is regularised toward the global mean.
    """
    print("  [Figure 2] Shrinkage plot …")

    # ── Hierarchical ─────────────────────────────────────────────────────────
    ds_h       = open_posterior(RESULTS / "idata.nc")
    bm_h       = ds_h["beta_m_by_measure"].values     # (chain, draw, measure)
    beta_g     = ds_h["beta_time"].values.ravel()     # global time effect
    meas_coords = list(ds_h.coords["measure"].values)
    ds_h.close()

    n_meas    = len(meas_coords)
    flat_h    = bm_h.reshape(-1, n_meas)
    h_mean    = flat_h.mean(0)
    g_mean    = float(beta_g.mean())

    # ── No-pooling ────────────────────────────────────────────────────────────
    nopool_nc = RESULTS / "idata_nopooling.nc"
    if nopool_nc.exists():
        ds_np     = open_posterior(nopool_nc)
        np_mean   = ds_np["beta_m"].values.reshape(-1, n_meas).mean(0)
        ds_np.close()
        np_label  = "No-pooling posterior mean"
    else:
        y, time_c, id_idx, meas_idx, n_id, _, _ = prepare_data()
        np_mean = np.zeros(n_meas)
        for m in range(n_meas):
            mask = meas_idx == m
            ym, tm = y[mask], time_c[mask]
            np_mean[m] = ym[tm > 0].mean() - ym[tm < 0].mean()
        np_label = "No-pooling (raw sample mean)"

    # ── Draw ──────────────────────────────────────────────────────────────────
    fig, ax = plt.subplots(figsize=(6.8, 6.0))

    # Axis limits: symmetric, slightly padded
    bound = max(np.abs(np_mean).max(), np.abs(h_mean).max()) * 1.55
    bound = max(bound, 0.20)
    ax.set_xlim(-bound, bound)
    ax.set_ylim(-bound, bound)

    # Reference: y = x (no shrinkage)
    ax.plot([-bound, bound], [-bound, bound],
            color=C_LGRAY, lw=1.1, linestyle="--", zorder=1, label="$y = x$  (no shrinkage)")

    # Reference: horizontal global mean
    ax.axhline(g_mean, color=C_GRAY, lw=1.0, linestyle=":",
               zorder=1, label=f"Global posterior mean  β = {g_mean:.3f}")

    # Arrows: from (np, np) on the diagonal → (np, hier)
    for m in range(n_meas):
        shrink = h_mean[m] - np_mean[m]        # vertical distance
        if abs(shrink) > 1e-4:
            ax.annotate(
                "",
                xy=(np_mean[m], h_mean[m]),    # arrowhead
                xytext=(np_mean[m], np_mean[m]),  # tail (on diagonal)
                arrowprops=dict(
                    arrowstyle="-|>",
                    color=C_HIER,
                    lw=1.6,
                    mutation_scale=10,
                ),
                zorder=3,
            )

    # No-pooling positions on the diagonal (red diamonds)
    ax.scatter(np_mean, np_mean, color=C_NP, marker="D", s=55, zorder=4,
               label=np_label)

    # Hierarchical positions (blue circles)
    ax.scatter(np_mean, h_mean, color=C_HIER, s=60, zorder=5,
               label="Hierarchical posterior mean")

    # Point labels (offset to avoid overlap)
    for m, lbl in enumerate(meas_coords):
        ax.annotate(
            lbl,
            xy=(np_mean[m], h_mean[m]),
            xytext=(5, 4),
            textcoords="offset points",
            fontsize=8.5,
            color="#222222",
        )

    ax.set_xlabel(f"{np_label}  " + r"($\beta_m$, SD units)", fontsize=11)
    ax.set_ylabel(r"Hierarchical posterior mean  ($\beta_m$, SD units)", fontsize=11)
    ax.set_title(
        "Hierarchical Shrinkage of Measure-Specific Time Effects\n"
        "(Arrows show regularisation toward the global mean)",
        fontsize=11, pad=10
    )
    ax.legend(loc="upper left", fontsize=9, framealpha=0.9, edgecolor=C_LGRAY)

    fig.tight_layout()
    out = FIGURES / "shrinkage_plot.png"
    fig.savefig(str(out), dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"    → {out}")


