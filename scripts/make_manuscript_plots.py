def plot_forest():
    """
    Horizontal forest plot of the measure-specific time effects β_m.

    Each measure occupies one row. Blue (hierarchical, partial pooling) and
    red (no-pooling) estimates are vertically offset within the row.
    The thick segment is the 50 % HDI; the thin line is the 94 % HDI; the
    filled symbol is the posterior mean.

    If idata_nopooling.nc is not yet available, the no-pooling column falls
    back to the raw sample-mean difference (equivalent to a frequentist
    paired-t effect size in standardised units).
    """
    print("  [Figure 1] Forest plot …")

    # ── Hierarchical β_m from idata.nc ────────────────────────────────────────
    ds_h  = open_posterior(RESULTS / "idata.nc")
    bm_h  = ds_h["beta_m_by_measure"].values          # (chain, draw, measure)
    meas_coords = list(ds_h.coords["measure"].values)
    ds_h.close()

    n_meas  = len(meas_coords)
    flat_h  = bm_h.reshape(-1, n_meas)                # (S, M)
    h_mean  = flat_h.mean(0)
    h94     = np.array([hdi(flat_h[:, m], 0.94) for m in range(n_meas)])
    h50     = np.array([hdi(flat_h[:, m], 0.50) for m in range(n_meas)])

    # ── No-pooling β_m ────────────────────────────────────────────────────────
    nopool_nc = RESULTS / "idata_nopooling.nc"
    if nopool_nc.exists():
        ds_np   = open_posterior(nopool_nc)
        bm_np   = ds_np["beta_m"].values.reshape(-1, n_meas)
        ds_np.close()
        np_mean  = bm_np.mean(0)
        np94     = np.array([hdi(bm_np[:, m], 0.94) for m in range(n_meas)])
        np50     = np.array([hdi(bm_np[:, m], 0.50) for m in range(n_meas)])
        np_label = "No-pooling"
    else:
        # Fallback: raw standardised pre-post difference per measure
        y, time_c, id_idx, meas_idx, n_id, _, _ = prepare_data()
        np_mean  = np.zeros(n_meas)
        np_se    = np.zeros(n_meas)
        for m in range(n_meas):
            mask  = meas_idx == m
            ym, tm = y[mask], time_c[mask]
            diffs  = ym[tm > 0] - ym[tm < 0]
            np_mean[m] = diffs.mean()
            np_se[m]   = diffs.std(ddof=1) / np.sqrt(len(diffs))
        # t_{n−1} ≈ 34 df: 94 % ↔ ±2.10 SE, 50 % ↔ ±0.68 SE
        np94 = np.column_stack([np_mean - 2.10 * np_se, np_mean + 2.10 * np_se])
        np50 = np.column_stack([np_mean - 0.68 * np_se, np_mean + 0.68 * np_se])
        np_label = "No-pooling (raw)"

    # ── Draw ──────────────────────────────────────────────────────────────────
    fig, ax = plt.subplots(figsize=(8.0, 6.4))
    OFFSET = 0.18  # vertical jitter between the two model estimates per row

    # ROPE band (drawn first so it sits behind the estimates)
    ax.axvspan(ROPE_LO, ROPE_HI, color="#d9d9d9", alpha=0.55, zorder=0,
               label=f"ROPE  [{ROPE_LO}, {ROPE_HI}] SD")

    for m in range(n_meas):
        row  = n_meas - 1 - m          # top-to-bottom layout
        y_h  = row + OFFSET
        y_np = row - OFFSET

        # ── hierarchical ──────────────────────────────────────────────────
        ax.plot(h94[m],  [y_h,  y_h],  color=C_HIER, lw=1.2, zorder=2)
        ax.plot(h50[m],  [y_h,  y_h],  color=C_HIER, lw=3.8, zorder=3,
                solid_capstyle="round")
        ax.scatter(h_mean[m], y_h, color=C_HIER, s=55, zorder=4)

        # ── no-pooling ────────────────────────────────────────────────────
        ax.plot(np94[m],  [y_np, y_np], color=C_NP,   lw=1.2, zorder=2)
        ax.plot(np50[m],  [y_np, y_np], color=C_NP,   lw=3.8, zorder=3,
                solid_capstyle="round")
