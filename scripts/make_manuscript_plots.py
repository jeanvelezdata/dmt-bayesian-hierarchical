def plot_ppc():
    """
    Two-panel figure: prior predictive check (left) and posterior predictive
    check (right).

    Each panel shows the observed standardised score distribution (bold black
    line) against 300 light KDE traces of replicated datasets y_rep, plus the
    mean replicated KDE (coloured dashed line).

    Posterior predictive is reconstructed from the posterior draws already
    stored in idata.nc using the full linear predictor:
        y_rep ~ Normal(α + β·t + RE_id_{i,0} + RE_id_{i,1}·t
                        + u0_m + u1_m·t,  σ)
    No PyMC re-run is needed.

    Prior predictive is generated by independently sampling each parameter
    from its prior and propagating through the same predictor.
    """
    print("  [Figure 3] PPC plot …")
    RNG = np.random.default_rng(42)

    # ── Observed data ─────────────────────────────────────────────────────────
    y_obs, time_c, id_idx, meas_idx, n_id, n_meas, _ = prepare_data()
    n_obs = len(y_obs)
    x_grid = np.linspace(-4.5, 4.5, 400)
    kde_obs = gaussian_kde(y_obs, x_grid)

    # ── Posterior predictive ─────────────────────────────────────────────────
    ds   = open_posterior(RESULTS / "idata.nc")
    alpha_all  = ds["alpha"].values.ravel()          # (S,)
    beta_all   = ds["beta_time"].values.ravel()      # (S,)
    RE_id_all  = ds["RE_id"].values                  # (chain, draw, id, 2)
    u0_m_all   = ds["u0_m"].values                   # (chain, draw, measure)
    u1_m_all   = ds["u1_m"].values                   # (chain, draw, measure)
    sigma_all  = ds["sigma"].values.ravel()          # (S,)
    n_chains, n_draws_per = ds["alpha"].shape
    ds.close()

    S = n_chains * n_draws_per
    RE_flat  = RE_id_all.reshape(S, n_id, 2)
    u0_flat  = u0_m_all.reshape(S, n_meas)
    u1_flat  = u1_m_all.reshape(S, n_meas)

    # Subsample to n_rep evenly-spaced draws for speed
    n_rep   = 300
    step    = max(1, S // n_rep)
    s_idx   = np.arange(0, S, step)[:n_rep]

    post_kdes = _posterior_predictive_kdes(
        y_obs,
        time_c,
        id_idx,
        meas_idx,
        alpha_all,
        beta_all,
        RE_flat,
        u0_flat,
        u1_flat,
        sigma_all,
        s_idx,
        x_grid,
        RNG,
    )

    # ── Prior predictive ─────────────────────────────────────────────────────
    # Forward-sample each parameter independently from its prior
    prior_kdes = np.empty((n_rep, len(x_grid)))
    for k in range(n_rep):
        alpha_s  = RNG.normal(0.0, 1.0)
        beta_s   = RNG.normal(0.0, 1.0)
        sigma_s  = np.abs(RNG.normal(0.0, 1.0))            # HalfNormal(1.0)
        sig_id   = np.abs(RNG.normal(0.0, 0.75, 2))        # HalfNormal(0.75) × 2
        # subject intercepts and slopes (independent; corr ignored in prior)
        b0_i     = RNG.normal(0.0, sig_id[0], n_id)
        b1_i     = RNG.normal(0.0, sig_id[1], n_id)
        # measure random effects
        sd_u0    = np.abs(RNG.normal(0.0, 0.75))
        sd_u1    = np.abs(RNG.normal(0.0, 0.75))
        u0_m_s   = RNG.normal(0.0, sd_u0, n_meas)
        u1_m_s   = RNG.normal(0.0, sd_u1, n_meas)

        mu = (
            alpha_s
            + beta_s     * time_c
            + b0_i[id_idx]
            + b1_i[id_idx] * time_c
            + u0_m_s[meas_idx]
            + u1_m_s[meas_idx] * time_c
        )
        y_rep = RNG.normal(mu, sigma_s).astype(float)
        prior_kdes[k] = gaussian_kde(y_rep, x_grid)

    # ── Draw ──────────────────────────────────────────────────────────────────
    fig, axes = plt.subplots(1, 2, figsize=(10.5, 4.5), sharey=True)

    for ax, kdes, mean_color, panel_title in [
        (axes[0], prior_kdes,  C_NP,   "Prior Predictive Check"),
        (axes[1], post_kdes,   C_HIER, "Posterior Predictive Check"),
    ]:
        # Individual replicated KDEs (light band)
        for k in range(n_rep):
            ax.plot(x_grid, kdes[k], color=C_BAND, alpha=0.06, lw=0.7, zorder=1)
        # Mean replicated KDE
        ax.plot(x_grid, kdes.mean(0), color=mean_color, lw=1.8,
                linestyle="--", zorder=3, label=r"Mean replicated $\hat{y}$")
        # Observed KDE
        ax.plot(x_grid, kde_obs, color="black", lw=2.2, zorder=4,
                label="Observed data")

        ax.set_xlim(-4.5, 4.5)
        ax.set_xlabel("Standardised Score (z)", fontsize=11)
        ax.set_title(panel_title, fontsize=11, pad=8)
        ax.legend(fontsize=9, framealpha=0.9, edgecolor=C_LGRAY, loc="upper right")

    axes[0].set_ylabel("Density", fontsize=11)
    fig.suptitle(
        "Predictive Checks — All Outcome Measures Combined\n"
        "(light traces = individual replicated datasets; bold = observed)",
        fontsize=10, y=1.01
    )

    fig.tight_layout()
    out = FIGURES / "ppc_plot.png"
    fig.savefig(str(out), dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"    → {out}")


