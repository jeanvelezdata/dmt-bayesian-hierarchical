# ─────────────────────────────────────────────────────────────────────────────

def plot_figure_s1_trace_rhat():
    """
    Figure S1: trace plots for key structural / measure-level parameters and a
    histogram of Gelman--Rubin R̂ for the same set (plus u0_m, u1_m, z_u0, z_u1).

    Latent subject-level arrays (z_id, RE_id) are omitted to keep the figure readable.
    """
    print("  [Figure S1] Trace plots + " + r"$\hat{R}$ …")

    idata_path = RESULTS / "idata.nc"
    if not idata_path.exists():
        raise FileNotFoundError(f"Missing {idata_path}")

    idata = az.from_netcdf(str(idata_path))
    ds = idata.posterior

    trace_vars = [
        "alpha",
        "beta_time",
        "sigma",
        "sd_u0",
        "sd_u1",
        "sigma_id",
        "corr_id",
        "beta_m_by_measure",
    ]
    present = [v for v in trace_vars if v in ds.data_vars]

    n_trace = len(present)
    fig, axes = plt.subplots(
        n_trace + 1,
        1,
        figsize=(10, 1.65 * n_trace + 2.4),
        gridspec_kw={"height_ratios": [1.15] * n_trace + [1.0]},
    )
    if n_trace == 0:
        raise RuntimeError("No trace variables found in idata.posterior")

    axes = np.atleast_1d(axes)

    for ax, name in zip(axes[:-1], present):
        _plot_chains_on_ax(ax, ds[name].values, name)
        ax.set_ylabel("value", fontsize=8)

    summ_vars = [
        "alpha",
        "beta_time",
        "sigma",
        "sd_u0",
        "sd_u1",
        "sigma_id",
        "corr_id",
        "beta_m_by_measure",
        "u0_m",
        "u1_m",
        "z_u0",
        "z_u1",
    ]
    summ_vars = [v for v in summ_vars if v in ds.data_vars]
    summ = az.summary(idata, var_names=summ_vars, hdi_prob=0.94)
    r_hat = summ["r_hat"].values.astype(float)
    r_hat = r_hat[np.isfinite(r_hat)]

    axr = axes[-1]
    nb = min(40, max(10, len(r_hat) // 2))
    axr.hist(r_hat, bins=nb, color=C_HIER, edgecolor="white", alpha=0.9)
    axr.axvline(1.0, color="black", ls="--", lw=1)
    axr.axvline(1.01, color=C_NP, ls=":", lw=1, label="1.01 (common rule-of-thumb)")
    axr.set_xlabel(r"$\hat{R}$", fontsize=10)
    axr.set_ylabel("Count", fontsize=10)
    axr.set_title(
        r"$\hat{R}$ across monitored structural + measure-level parameters "
        r"(excludes z_id / RE_id)",
        fontsize=9,
    )
    axr.legend(fontsize=8, loc="upper right")

    fig.suptitle(
        r"Figure S1 — Convergence diagnostics (traces + $\hat{R}$)",
        fontsize=12,
        y=1.01,
    )
    fig.tight_layout()
    out = FIGURES / "figure_S1_trace_rhat.png"
    fig.savefig(str(out), dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"    → {out}")


