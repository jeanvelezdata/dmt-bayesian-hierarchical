# Colours for the three prior specifications
C_SPEC_A = "#2171b5"   # blue   — Spec A (default)
C_SPEC_B = "#d94801"   # orange — Spec B (tighter priors, SDs halved)
C_SPEC_C = "#31a354"   # green  — Spec C (wider priors, SDs doubled)

ROPE_LO, ROPE_HI = -0.10, 0.10   # matches manuscript_analyses.py task6


def plot_figure_4_sensitivity_forest():
    """
    Figure 4: sensitivity forest plot for the prior robustness analysis (Q2).

    Each row is one outcome measure; three point-range displays are drawn
    within the row — one per prior specification (A, B, C) — vertically
    offset so they never overlap.  A shared ROPE band [−0.1, 0.1] is shown
    as a light grey rectangle.  The 94 % HDI is shown as a thin horizontal
    line; the posterior mean as a filled circle.

    Data are read from ``results/sensitivity_results.csv`` which is written
    by ``manuscript_analyses.py`` (task4_sensitivity).  The function also
    attempts to load the raw posterior draws from ``idata_spec_b.nc`` /
    ``idata_spec_c.nc`` to draw the 50 % HDI (thick bar) in the same style
    as Figure 1; if those files are absent it falls back to the CSV summaries
    only (thin line + point).
    """
    print("  [Figure 4] Sensitivity forest plot …")

    csv_path = RESULTS / "sensitivity_results.csv"
    if not csv_path.exists():
        raise FileNotFoundError(
            f"Missing {csv_path} — run manuscript_analyses.py task4 first."
        )

    df = pd.read_csv(csv_path)
    measures = df["measure"].tolist()
    n_meas = len(measures)

    # ── Posterior means and 94 % HDIs from CSV ────────────────────────────────
    specs = {
        "A": {
            "mean":   df["spec_a_mean"].values,
            "hdi_lo": df["spec_a_hdi_lo"].values,
            "hdi_hi": df["spec_a_hdi_hi"].values,
            "color":  C_SPEC_A,
            "label":  "Spec A  (default)",
            "offset": +0.22,
        },
        "B": {
            "mean":   df["spec_b_mean"].values,
            "hdi_lo": df["spec_b_hdi_lo"].values,
            "hdi_hi": df["spec_b_hdi_hi"].values,
            "color":  C_SPEC_B,
            "label":  "Spec B  (tighter: SDs × ½)",
            "offset":  0.00,
        },
        "C": {
            "mean":   df["spec_c_mean"].values,
            "hdi_lo": df["spec_c_hdi_lo"].values,
            "hdi_hi": df["spec_c_hdi_hi"].values,
            "color":  C_SPEC_C,
            "label":  "Spec C  (wider: SDs × 2)",
            "offset": -0.22,
        },
    }

    # ── Optional: 50 % HDI from raw draws ────────────────────────────────────
    spec_nc = {
        "A": RESULTS / "idata.nc",
        "B": RESULTS / "idata_spec_b.nc",
        "C": RESULTS / "idata_spec_c.nc",
    }
    for key, info in specs.items():
        nc = spec_nc[key]
        info["hdi50"] = None
        if nc.exists():
            try:
                ds = open_posterior(nc)
                # prefer beta_m_by_measure (hierarchical); fall back to beta_m
                if "beta_m_by_measure" in ds.data_vars:
                    bm = ds["beta_m_by_measure"].values.reshape(-1, n_meas)
                elif "beta_m" in ds.data_vars:
                    bm = ds["beta_m"].values.reshape(-1, n_meas)
                else:
                    bm = None
                ds.close()
                if bm is not None:
                    info["hdi50"] = np.array(
                        [hdi(bm[:, m], 0.50) for m in range(n_meas)]
                    )
            except Exception:
                pass   # silently fall back to CSV-only display

    # ── Draw ──────────────────────────────────────────────────────────────────
    fig, ax = plt.subplots(figsize=(8.5, 6.8))

    # ROPE band (drawn first so it sits behind the estimates)
    ax.axvspan(ROPE_LO, ROPE_HI, color="#d9d9d9", alpha=0.55, zorder=0,
               label=f"ROPE  [{ROPE_LO}, {ROPE_HI}] SD")

    # Zero reference
    ax.axvline(0, color=C_GRAY, lw=0.9, linestyle="--", zorder=1)

    for m in range(n_meas):
        row = n_meas - 1 - m   # top-to-bottom layout

        for info in specs.values():
            y_pos   = row + info["offset"]
            lo, hi  = float(info["hdi_lo"][m]), float(info["hdi_hi"][m])
            mn      = float(info["mean"][m])
            col     = info["color"]

            # 94 % HDI — thin line
            ax.plot([lo, hi], [y_pos, y_pos], color=col, lw=1.2, zorder=2)

            # 50 % HDI — thick bar (if available from raw draws)
            if info["hdi50"] is not None:
                h50_lo, h50_hi = info["hdi50"][m]
                ax.plot([h50_lo, h50_hi], [y_pos, y_pos],
                        color=col, lw=3.8, zorder=3, solid_capstyle="round")

            # Posterior mean — filled circle
            ax.scatter(mn, y_pos, color=col, s=48, zorder=4)

    # y-axis measure labels
    ax.set_yticks(np.arange(n_meas))
    ax.set_yticklabels(list(reversed(measures)), fontsize=10)
    ax.set_ylim(-0.65, n_meas - 0.35)

    # Legend
    legend_handles = [
        mpatches.Patch(color=info["color"], label=info["label"])
        for info in specs.values()
    ] + [
        mpatches.Patch(color="#d9d9d9", alpha=0.75,
                       label=f"ROPE  [{ROPE_LO}, {ROPE_HI}] SD"),
        plt.Line2D([0], [0], lw=1.2, color=C_GRAY, linestyle="--",
                   label="Zero reference"),
        plt.Line2D([0], [0], lw=3.8, color=C_GRAY,
                   label="Thick bar = 50 % HDI", solid_capstyle="round"),
        plt.Line2D([0], [0], lw=1.2, color=C_GRAY,
                   label="Thin line = 94 % HDI"),
    ]
    fig.legend(handles=legend_handles, loc="lower center",
               bbox_to_anchor=(0.5, -0.02), ncol=3,
               fontsize=9, framealpha=0.9, edgecolor=C_LGRAY)

    ax.set_xlabel(
        r"Standardised Pre-to-Post Change ($\beta_m$, SD units)", fontsize=11
    )
    ax.set_ylabel("Outcome Measure", fontsize=11)
    ax.set_title(
        "Figure 4 — Prior Sensitivity: $\\beta_m$ Posteriors Across\n"
        "Three Prior Specifications (A = default, B = tighter, C = wider)",
        fontsize=11, pad=10,
    )

    fig.tight_layout()
    fig.subplots_adjust(bottom=0.18)
    out = FIGURES / "figure_4_sensitivity_forest.png"
    fig.savefig(str(out), dpi=300, bbox_inches="tight")
    plt.close(fig)
    print(f"    → {out}")


