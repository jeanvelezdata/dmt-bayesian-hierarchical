def hdi(samples: np.ndarray, prob: float = 0.94) -> tuple[float, float]:
    """
    Highest Density Interval — pure numpy, no scipy.
    For nearly Gaussian posteriors this is essentially the same as an
    equal-tailed CI; it differs only in the tails for skewed posteriors.
    """
    s = np.sort(np.ravel(samples).astype(float))
    n = len(s)
    n_in  = int(np.floor(prob * n))
    n_out = n - n_in
    if n_out == 0:
        return float(s[0]), float(s[-1])
    widths  = s[n_in:] - s[:n_out]
    lo_idx  = int(np.argmin(widths))
    return float(s[lo_idx]), float(s[lo_idx + n_in])


def gaussian_kde(data: np.ndarray, x_grid: np.ndarray, bw: float | None = None) -> np.ndarray:
    """
    Gaussian kernel density estimate evaluated on x_grid — pure numpy.
    Uses Silverman's rule for bandwidth selection.
    """
    d = np.ravel(data).astype(float)
    d = d[np.isfinite(d)]
    if len(d) < 2:
        return np.zeros_like(x_grid)
    if bw is None:
        bw = 1.06 * d.std(ddof=1) * len(d) ** (-0.2)
    bw = max(bw, 0.02)
    # (grid_pts,) kernel evaluated at each x_grid point
    z = (x_grid[:, None] - d[None, :]) / bw       # (G, N)
    kde = np.exp(-0.5 * z ** 2).sum(axis=1) / (len(d) * bw * np.sqrt(2 * np.pi))
    return kde


def open_posterior(nc_path: Path) -> xr.Dataset:
    """Open only the 'posterior' group of an ArviZ-style NetCDF file."""
    return xr.open_dataset(str(nc_path), group="posterior")


def _plot_chains_on_ax(ax, vals: np.ndarray, title: str) -> None:
    """Trace-style line plots: vals shape (chain, draw) or (chain, draw, K)."""
    vals = np.asarray(vals, dtype=float)
    if vals.ndim == 2:
        for c in range(vals.shape[0]):
            ax.plot(vals[c], lw=0.45, alpha=0.75)
    elif vals.ndim == 3:
        n_last = vals.shape[-1]
        cmap = plt.cm.tab10(np.linspace(0, 1, min(n_last, 10)))
        for k in range(n_last):
            for c in range(vals.shape[0]):
                ax.plot(vals[c, :, k], lw=0.4, alpha=0.55, color=cmap[k % 10])
    else:
        ax.text(0.5, 0.5, f"(unexpected ndim={vals.ndim})", ha="center", va="center", transform=ax.transAxes)
    ax.set_title(title, fontsize=9)
    if vals.ndim >= 2:
        ax.set_xlim(0, max(vals.shape[1] - 1, 1))
    ax.tick_params(labelsize=7)


def prepare_data():
    """Load + reshape + standardize data; return arrays and metadata."""
    df       = load_data(str(REPO / "data" / "scales_results.csv"))
    varmap   = build_varmap(df)
    dat_long, measure_order = reshape_long(df, varmap)
    dat_long, _             = standardize_within_measure(dat_long)
    dat_long["time_c"]      = np.where(dat_long["time"] == "pre", -0.5, 0.5)

    id_cat   = pd.Categorical(dat_long["id"])
    meas_cat = dat_long["measure"].cat.codes.values

    y        = dat_long["z"].values.astype(float)
    time_c   = dat_long["time_c"].values.astype(float)
    id_idx   = id_cat.codes.astype(int)
    meas_idx = meas_cat.astype(int)
    n_id     = int(id_cat.categories.size)
    n_meas   = len(measure_order)

    return y, time_c, id_idx, meas_idx, n_id, n_meas, measure_order


def _posterior_predictive_kdes(
    y_obs: np.ndarray,
    time_c: np.ndarray,
    id_idx: np.ndarray,
    meas_idx: np.ndarray,
    alpha_all: np.ndarray,
    beta_all: np.ndarray,
    RE_flat: np.ndarray,
    u0_flat: np.ndarray,
    u1_flat: np.ndarray,
    sigma_all: np.ndarray,
    s_idx: np.ndarray,
    x_grid: np.ndarray,
    RNG: np.random.Generator,
) -> np.ndarray:
    """
    For each posterior draw index in s_idx, simulate y_rep and return KDE curves
    stacked as (len(s_idx), len(x_grid)).
    """
    n_rep = len(s_idx)
    post_kdes = np.empty((n_rep, len(x_grid)))
    for k, s in enumerate(s_idx):
        mu = (
            alpha_all[s]
            + beta_all[s] * time_c
            + RE_flat[s, id_idx, 0]
            + RE_flat[s, id_idx, 1] * time_c
            + u0_flat[s, meas_idx]
            + u1_flat[s, meas_idx] * time_c
        )
        y_rep = RNG.normal(mu, sigma_all[s]).astype(float)
        post_kdes[k] = gaussian_kde(y_rep, x_grid)
    return post_kdes


